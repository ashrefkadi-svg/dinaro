/** All numeric state comes from read-only progress; this module NEVER changes money. */
export function sceneFromProgress(progress:number,previousProgress?:number):DialogueScene{
  if(!Number.isFinite(progress))throw new RangeError("Progress must be finite");
  const p=Math.min(100,Math.max(0,progress));
  if(p>=100)return "victory";
  if(previousProgress!==undefined && Number.isFinite(previousProgress) && p<previousProgress)return "setback";
  if(previousProgress!==undefined && Number.isFinite(previousProgress) && p===previousProgress)return "slowdown";
  if([25,50,75].some(m=>p===m))return "milestone";
  return p<25?"early":"growing";
}

export interface DialogueRequest {
  npc:NpcId;
  scene:DialogueScene;
  turn:number;
  lastVariant?:number;
  choice?:PlayerIntent;
}

export interface DialogueReply {
  npc:NpcId;
  name:string;
  role:string;
  scene:DialogueScene;
  variant:number;
  text:string;
  prompt:string;
}

/**
 * Rotate across 3 authored phrasings, preserving per-session turn index.
 * Previous variant is excluded when possible. No false claims of memory or AI.
 */
export function chooseDialogue(req:DialogueRequest):DialogueReply{
  const character=NPC_CAST[req.npc];
  if(!character)throw new RangeError("Unknown NPC");
  if(!DIALOGUE_SCENES.includes(req.scene))throw new RangeError("Unknown dialogue scene");
  if(req.choice && !PLAYER_INTENTS.includes(req.choice))throw new RangeError("Unknown player choice");
  if(!Number.isSafeInteger(req.turn)||req.turn<0)throw new RangeError("Turn must be a nonnegative integer");
  const lines=req.choice?character.choices[req.choice]:character.lines[req.scene];
  let variant=req.turn%lines.length;
  if(req.lastVariant!==undefined && variant===req.lastVariant)variant=(variant+1)%lines.length;
  return {
    npc:req.npc,name:character.name,role:character.role,scene:req.scene,
    variant,text:lines[variant],
    prompt:req.choice===undefined?"تحب نكملو الحديث؟":"تقدر تختار موضوعًا آخر أو ترجع للاستكشاف."
  };
}
